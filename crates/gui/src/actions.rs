/// A row context-menu item. `token` names the `ConversationTarget` that
/// `ListPane` captured when it built the menu (§5.2), so the item never acts
/// on the live selection (A1).
#[derive(Clone, PartialEq, Debug, gpui_kit::Action)]
#[action(namespace = history, no_json)]
pub struct RowMenu {
    pub item: RowMenuItem,
    pub token: u64,
}

